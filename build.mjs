#!/usr/bin/env node
/* Builds the single-file game (index.html) from src/.
     node build.mjs          build index.html (minified) and docs/MODULES.md
     node build.mjs --dev    unminified build, easier to debug in the browser
     node build.mjs --check  fail if index.html or docs/MODULES.md is out of date with src/ (CI)
     node build.mjs --trailer  out/trailer.html only: the game plus the cinematic trailer, for recording it */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import { transformSync } from "esbuild";
import { ROOT, read, readScript, manifest, declarations, engineFiles, isEsm } from "./tools/modules.mjs";

const simBundle = createRequire(import.meta.url)("./tools/sim-bundle.cjs");

/** trailer: also include the trailer's modules, markup and styles (manifest.trailer); the game itself never ships them */
export function build({ dev = false, trailer = false } = {}) {
  const man = manifest(),
    tr = man.trailer;
  const mod = p => `/* ---- ${p} ---- */\n${readScript(p).replace(/\s+$/, "")}\n`;
  const js = code =>
    dev
      ? code
      : transformSync(code, { loader: "js", minify: true, target: "es2020", legalComments: "none" }).code;
  const css = code => (dev ? code : transformSync(code, { loader: "css", minify: true }).code);
  /* markup: comments (but the build's own directives) and indentation dropped; a line break still
     separates what it separated, so spacing between inline elements is unchanged */
  const markup = s => (dev ? s : s.replace(/<!--(?!@)[\s\S]*?-->/g, "").replace(/\n\s+/g, "\n"));
  /* the trailer build appends its engine modules (they share the engine's scope, after game/exports.js) */
  const engine = [...man.engine, ...(trailer ? tr.engine : [])].map(mod).join(""),
    modes = [...man.modes, ...(trailer ? tr.modes : [])].map(mod).join("");
  /* dev builds switch on the developer console (press backquote) */
  const game = js(`${dev ? "window.KA_DEV = true;\n" : ""}(() => {\n"use strict";\n${engine}})();\n${modes}`);
  const html = markup(read("html/index.html"))
    .replace("<!--@styles-->", () => css([...man.styles, ...(trailer ? tr.styles : [])].map(read).join("\n")))
    .replace("<!--@trailer-->\n", () => (trailer ? markup(read(tr.html)) : ""))
    .replace(/<!--@partial ([\w./-]+)-->/g, (_, p) => markup(read(p)).replace(/\s+$/, ""))
    .replace(/<!--@script ([\w./-]+)-->/g, (_, p) => `<script>\n${js(mod(p))}</script>`)
    .replace("<!--@three-->", () => threeTags(man.three))
    /* a module, so it runs after three.js has loaded (module scripts run in document order) */
    .replace("<!--@game-->", () => `<script type="module">\n${game}</script>\n</body>\n</html>\n`);
  const problems = [];
  if (/<\/script/i.test(game)) problems.push("a module contains a closing script tag");
  if (/<!--@/.test(html)) problems.push("unresolved template directive");
  if (problems.length) throw new Error("build failed:\n  " + problems.join("\n  "));
  /* module index for contributors: what each file declares at top level */
  let doc =
    "# Module index\n\nGenerated by `node build.mjs`. Do not edit by hand.\n\n" +
    "Engine modules share one scope and load in this order; mode modules are self-contained and use `window.KA`.\n\n" +
    "| Module | Lines | Top-level declarations |\n|---|---|---|\n";
  for (const p of [...engineFiles(), ...man.modes, ...tr.modes]) {
    const s = read(p),
      d = declarations(s);
    doc += `| \`src/${p}\` | ${s.split("\n").length} | ${d
      .slice(0, 18)
      .map(x => "`" + x + "`")
      .join(" ")}${d.length > 18 ? ` … (+${d.length - 18})` : ""} |\n`;
  }
  /* the background simulation worker ships next to index.html (pages served over http/https use it;
     opened as a file, the game falls back to simulating on the main thread) */
  const worker = js(simBundle(read, man));
  return {
    html,
    doc,
    sandbox: sandboxDoc(),
    types: esmTypes(),
    worker,
    modules: man.engine.length + man.modes.length + (trailer ? tr.engine.length + tr.modes.length : 0),
  };
}

/** three.js, pinned (manifest.three), from jsDelivr: its ES module build sets the global THREE the engine
    reads. three.module.min.js imports "./three.core.js"; the import map points that at the minified core,
    so the page downloads about 0.8 MB of minified script instead of 2.1 MB (and the CDN compresses it).
    A test stub served in its place may have set THREE already. "three" is mapped too, so addons loaded
    on demand from the same CDN (examples/jsm, e.g. SMAA in render/pipeline.js) share this instance;
    window.THREE_URL is the build folder they are found beside. */
export function threeTags(v) {
  const base = `https://cdn.jsdelivr.net/npm/three@${v}/build/`;
  return (
    `<script type="importmap">${JSON.stringify({ imports: { [base + "three.core.js"]: base + "three.core.min.js", three: base + "three.module.min.js" } })}</script>\n` +
    `<script type="module">import * as THREE from "${base}three.module.min.js";window.THREE ??= THREE;window.THREE_URL = "${base}";</script>`
  );
}

/** types/engine-modules.d.ts: an engine module written as an ES module is a module to TypeScript, but
    the script modules read its exports as shared-scope names; this declares them for those */
export function esmTypes() {
  let d =
    "/* Generated by `node build.mjs`: do not edit. Exports of the engine modules written as ES modules\n" +
    "   (tools/esm.cjs), declared for the script modules that use them as shared-scope names. */\n";
  for (const p of engineFiles())
    if (isEsm(read(p)))
      for (const n of declarations(read(p))) d += `declare const ${n}: typeof import("../src/${p}").${n};\n`;
  return d;
}

/** docs/SANDBOX.md: the kill-time table, computed from the same data the game uses */
export function sandboxDoc() {
  const ctx = {};
  vm.runInNewContext(
    read("data/weapons.js") +
      "\nthis.W = WEAPON_DATA; this.K = killStats; this.S = PILOT_SHIELD; this.H = PILOT_HEALTH;",
    ctx
  );
  let md =
    "# Sandbox: kill times\n\nGenerated by `node build.mjs` from `src/data/weapons.js`. Do not edit by hand.\n\n" +
    `Every pilot has ${ctx.S} shield and ${ctx.H} health. Shields absorb everything and damage past a broken shield carries into health. ` +
    "Headshots only count once shields are down, except on weapons marked *head always*. Precision weapons have no random spread: the shot goes exactly where the reticle is, moving or airborne.\n\n" +
    "| Weapon | Body | Head | Fire interval | Best kill (shots / time) | Body shots only | Precision |\n|---|---|---|---|---|---|---|\n";
  for (const w of ctx.W) {
    const k = ctx.K(w);
    md += `| ${w.name}${w.pellets ? ` (${w.pellets} pellets, at close range)` : ""} | ${w.body} | ${w.head >= 999 ? "kill" : w.head}${w.headAlways ? " (head always)" : ""} | ${w.rate} s | ${k.best.shots} / ${k.best.time} s | ${k.body.shots} / ${k.body.time} s | ${w.precision ? "yes" : "no (spread and bloom)"} |\n`;
  }
  md +=
    "\nFor pellet weapons, a shot is every pellet hitting at close range.\n" +
    "\n**Perfect** medal: a kill with a precision weapon in its minimum shot count with no missed shots in between (the magnum's is 4 body or head shots to break shields, then a headshot: 5 shots, 1.04 s).\n";
  return md;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1].endsWith("build.mjs")) {
  const dev = process.argv.includes("--dev"),
    trailer = process.argv.includes("--trailer");
  let res;
  try {
    res = build({ dev, trailer });
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
  const out = path.join(ROOT, "index.html"),
    docOut = path.join(ROOT, "docs", "MODULES.md"),
    sbOut = path.join(ROOT, "docs", "SANDBOX.md"),
    tyOut = path.join(ROOT, "types", "engine-modules.d.ts"),
    wkOut = path.join(ROOT, "sim-worker.js");
  if (trailer) {
    const f = path.join(ROOT, "out", "trailer.html");
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, res.html);
    console.log(`built out/trailer.html (${(res.html.length / 1024).toFixed(0)} KB)`);
    process.exit(0);
  }
  if (process.argv.includes("--check")) {
    const stale = [
      [out, res.html],
      [docOut, res.doc],
      [sbOut, res.sandbox],
      [tyOut, res.types],
      [wkOut, res.worker],
    ]
      .filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== c)
      .map(([f]) => path.relative(ROOT, f));
    if (stale.length) {
      console.error(`out of date: ${stale.join(", ")}. Run: node build.mjs`);
      process.exit(1);
    }
    console.log("index.html is up to date");
    process.exit(0);
  }
  fs.mkdirSync(path.dirname(docOut), { recursive: true });
  fs.writeFileSync(out, res.html);
  fs.writeFileSync(docOut, res.doc);
  fs.writeFileSync(sbOut, res.sandbox);
  fs.writeFileSync(tyOut, res.types);
  fs.writeFileSync(wkOut, res.worker);
  console.log(
    `built index.html${dev ? " (dev, unminified)" : ""} (${(res.html.length / 1024).toFixed(0)} KB, ${res.modules} modules)`
  );
}
