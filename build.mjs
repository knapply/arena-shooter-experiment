#!/usr/bin/env node
/* Builds the single-file game (index.html) from src/.
     node build.mjs          build index.html (minified) and docs/MODULES.md
     node build.mjs --dev    unminified build, easier to debug in the browser
     node build.mjs --check  fail if index.html or docs/MODULES.md is out of date with src/ (CI) */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { transformSync } from "esbuild";
import { ROOT, read, manifest, declarations } from "./tools/modules.mjs";

export function build({ dev = false } = {}) {
  const man = manifest();
  const mod = p => `/* ---- ${p} ---- */\n${read(p).replace(/\s+$/, "")}\n`;
  const js = code =>
    dev
      ? code
      : transformSync(code, { loader: "js", minify: true, target: "es2020", legalComments: "none" }).code;
  const css = code => (dev ? code : transformSync(code, { loader: "css", minify: true }).code);
  const engine = man.engine.map(mod).join(""),
    modes = man.modes.map(mod).join("");
  /* dev builds switch on the developer console (press backquote) */
  const game = js(`${dev ? "window.KA_DEV = true;\n" : ""}(() => {\n"use strict";\n${engine}})();\n${modes}`);
  const html = read("html/index.html")
    .replace("<!--@styles-->", () => css(man.styles.map(read).join("\n")))
    .replace(/<!--@partial ([\w./-]+)-->/g, (_, p) => read(p).replace(/\s+$/, ""))
    .replace(/<!--@script ([\w./-]+)-->/g, (_, p) => `<script>\n${js(mod(p))}</script>`)
    .replace("<!--@game-->", () => `<script>\n${game}</script>\n</body>\n</html>\n`);
  const problems = [];
  if (/<\/script/i.test(game)) problems.push("a module contains a closing script tag");
  if (/<!--@/.test(html)) problems.push("unresolved template directive");
  if (problems.length) throw new Error("build failed:\n  " + problems.join("\n  "));
  /* module index for contributors: what each file declares at top level */
  let doc =
    "# Module index\n\nGenerated by `node build.mjs`. Do not edit by hand.\n\n" +
    "Engine modules share one scope and load in this order; mode modules are self-contained and use `window.KA`.\n\n" +
    "| Module | Lines | Top-level declarations |\n|---|---|---|\n";
  for (const p of [...man.engine, ...man.modes]) {
    const s = read(p),
      d = declarations(s);
    doc += `| \`src/${p}\` | ${s.split("\n").length} | ${d
      .slice(0, 18)
      .map(x => "`" + x + "`")
      .join(" ")}${d.length > 18 ? ` … (+${d.length - 18})` : ""} |\n`;
  }
  return { html, doc, sandbox: sandboxDoc(), modules: man.engine.length + man.modes.length };
}

/** docs/SANDBOX.md: the kill-time table, computed from the same data the game uses */
export function sandboxDoc() {
  const ctx = {};
  vm.runInNewContext(
    read("data/weapons.js") +
      "\nthis.W = WEAPON_DATA; this.K = killStats; this.S = PILOT_SHIELD; this.H = PILOT_HEALTH;",
    ctx
  );
  let md =
    "# Sandbox: kill times\n\nGenerated by `node build.mjs` from `src/data/weapons.js`. Do not edit by hand.\n\n" +
    `Every pilot has ${ctx.S} shield and ${ctx.H} health. Shields absorb everything and damage past a broken shield carries into health. ` +
    "Headshots only count once shields are down, except on weapons marked *head always*. Precision weapons have no random spread: the shot goes exactly where the reticle is, moving or airborne.\n\n" +
    "| Weapon | Body | Head | Fire interval | Best kill (shots / time) | Body shots only | Precision |\n|---|---|---|---|---|---|---|\n";
  for (const w of ctx.W) {
    const k = ctx.K(w);
    md += `| ${w.name} | ${w.body} | ${w.head >= 999 ? "kill" : w.head}${w.headAlways ? " (head always)" : ""} | ${w.rate} s | ${k.best.shots} / ${k.best.time} s | ${k.body.shots} / ${k.body.time} s | ${w.precision ? "yes" : "no (spread and bloom)"} |\n`;
  }
  md +=
    "\n**Perfect** medal: a kill with a precision weapon in its minimum shot count with no missed shots in between (the magnum's is 4 body or head shots to break shields, then a headshot: 5 shots, 1.04 s).\n";
  return md;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1].endsWith("build.mjs")) {
  const dev = process.argv.includes("--dev");
  let res;
  try {
    res = build({ dev });
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
  const out = path.join(ROOT, "index.html"),
    docOut = path.join(ROOT, "docs", "MODULES.md"),
    sbOut = path.join(ROOT, "docs", "SANDBOX.md");
  if (process.argv.includes("--check")) {
    const stale = [
      [out, res.html],
      [docOut, res.doc],
      [sbOut, res.sandbox],
    ]
      .filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== c)
      .map(([f]) => path.relative(ROOT, f));
    if (stale.length) {
      console.error(`out of date: ${stale.join(", ")}. Run: node build.mjs`);
      process.exit(1);
    }
    console.log("index.html is up to date");
    process.exit(0);
  }
  fs.mkdirSync(path.dirname(docOut), { recursive: true });
  fs.writeFileSync(out, res.html);
  fs.writeFileSync(docOut, res.doc);
  fs.writeFileSync(sbOut, res.sandbox);
  console.log(
    `built index.html${dev ? " (dev, unminified)" : ""} (${(res.html.length / 1024).toFixed(0)} KB, ${res.modules} modules)`
  );
}
