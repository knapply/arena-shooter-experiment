#!/usr/bin/env node
/* Builds the single-file game (index.html) from src/.
   node build.mjs          build index.html and docs/MODULES.md
   node build.mjs --check  fail if index.html is out of date with src/ (used in CI) */
import fs from "node:fs";import path from "node:path";import {fileURLToPath} from "node:url";
const ROOT=path.dirname(fileURLToPath(import.meta.url)),SRC=path.join(ROOT,"src");
const read=p=>fs.readFileSync(path.join(SRC,p),"utf8");
const man=JSON.parse(read("manifest.json"));
const mod=p=>`/* ---- ${p} ---- */\n${read(p).replace(/\s+$/,"")}\n`;
const engine=man.engine.map(mod).join(""),modes=man.modes.map(mod).join("");
const game=`(() => {\n"use strict";\n${engine}})();\n${modes}`;
let html=read("html/index.html")
  .replace("<!--@styles-->",()=>man.styles.map(read).join("\n"))
  .replace(/<!--@partial ([\w./-]+)-->/g,(_,p)=>read(p).replace(/\s+$/,""))
  .replace(/<!--@script ([\w./-]+)-->/g,(_,p)=>`<script>\n${mod(p)}</script>`)
  .replace("<!--@game-->",()=>`<script>\n${game}</script>\n</body>\n</html>\n`);
const problems=[];
if(/<\/script/i.test(game))problems.push("a module contains a closing script tag");
for(const m of html.matchAll(/claude|anthropic|halo/gi))problems.push(`blocked word "${m[0]}" at offset ${m.index}`);
if(/<!--@/.test(html))problems.push("unresolved template directive");
if(problems.length){console.error("build failed:\n  "+problems.slice(0,10).join("\n  "));process.exit(1);}
/* module index for contributors: what each file declares at top level */
const decl=src=>[...src.matchAll(/^(?:async\s+)?(?:function\s+([\w$]+)|(?:const|let|class)\s+([\w$]+))/gm)].map(m=>m[1]||m[2]);
let doc="# Module index\n\nGenerated by `node build.mjs`. Do not edit by hand.\n\nEngine modules share one scope and load in this order; mode modules are self-contained and use `window.KA`.\n\n| Module | Lines | Top-level declarations |\n|---|---|---|\n";
for(const p of [...man.engine,...man.modes]){const s=read(p);doc+=`| \`src/${p}\` | ${s.split("\n").length} | ${decl(s).slice(0,18).map(x=>"`"+x+"`").join(" ")}${decl(s).length>18?" …":""} |\n`;}
const out=path.join(ROOT,"index.html"),docOut=path.join(ROOT,"docs","MODULES.md");
if(process.argv.includes("--check")){
  const stale=[[out,html],[docOut,doc]].filter(([f,c])=>!fs.existsSync(f)||fs.readFileSync(f,"utf8")!==c).map(([f])=>path.relative(ROOT,f));
  if(stale.length){console.error(`out of date: ${stale.join(", ")}. Run: node build.mjs`);process.exit(1);}
  console.log("index.html is up to date");process.exit(0);}
fs.mkdirSync(path.dirname(docOut),{recursive:true});fs.writeFileSync(out,html);fs.writeFileSync(docOut,doc);
console.log(`built index.html (${(html.length/1024).toFixed(0)} KB, ${man.engine.length+man.modes.length} modules)`);
